# ============================================================
# 5. QUEUE MODEL
# ============================================================

# Customers join the queue without receiving a token initially.
# Staff generates the token later.
#
# Example:
# Customer 1 -> Account Opening -> Waiting
# Customer 2 -> Loan             -> Waiting


class Queue(models.Model):

    STATUS_CHOICES = [
        ("waiting", "Waiting"),
        ("called", "Called"),
        ("serving", "Serving"),
        ("completed", "Completed"),
        ("cancelled", "Cancelled"),
        ("skipped", "Skipped"),
    ]

    # Customer who joined the queue
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name="queues")

    active_customer = models.OneToOneField(
        User,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="active_queue_entry",
    )

    # Keep attribution optional until a staff member calls this queue entry.
    # SET_NULL preserves the queue record if a staff account is ever removed.
    called_by = models.ForeignKey(
        User,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="called_queues",
    )
    called_at = models.DateTimeField(null=True, blank=True)
    grace_deadline = models.DateTimeField(null=True, blank=True)

    # Selected service
    service = models.CharField(max_length=100)

    # Expected duration entered by staff when service starts. Historical rows
    # remain valid and may not have this value.
    service_duration_minutes = models.PositiveIntegerField(null=True, blank=True)

    # Generated by staff later
    token_number = models.PositiveIntegerField(null=True, blank=True)

    queue_date = models.DateField(default=timezone.localdate)

    # Current queue status
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default="waiting")

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["created_at"]

        indexes = [
            models.Index(
                fields=["status", "created_at", "id"],
                name="queue_status_created_idx",
            )
        ]

        constraints = [
            models.UniqueConstraint(
                fields=["queue_date", "token_number"],
                name="unique_queue_token_per_day",
            )
        ]

    def save(self, *args, **kwargs):
        active_statuses = {"waiting", "called", "serving"}
        self.active_customer_id = (
            self.user_id if self.status in active_statuses else None
        )
        update_fields = kwargs.get("update_fields")
        if update_fields is not None:
            kwargs["update_fields"] = set(update_fields) | {"active_customer"}
        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.token or 'Not Generated'} - {self.user.username}"

    @property
    def token(self):
        """
        Converts token numbers into formatted tokens.

        1  -> A001
        2  -> A002
        10 -> A010
        """
        if self.token_number is None:
            return None

        return f"A{self.token_number:03d}"


